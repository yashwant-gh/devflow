from datetime import datetime, timezone

from app.schemas.item import ItemCreate, ItemResponse


class ItemsService:
    def __init__(self):
        self._items: dict[str, ItemResponse] = {
            "1": ItemResponse(
                id="1",
                name="Initial Item",
                description="Starter item generated by DevFlow",
                created_at=datetime.now(timezone.utc).isoformat(),
            )
        }

    def get_all(self) -> list[ItemResponse]:
        return list(self._items.values())

    def get_by_id(self, item_id: str) -> ItemResponse | None:
        return self._items.get(item_id)

    def create(self, data: ItemCreate) -> ItemResponse:
        new_id = str(len(self._items) + 1)
        item = ItemResponse(
            id=new_id,
            name=data.name,
            description=data.description,
            created_at=datetime.now(timezone.utc).isoformat(),
        )
        self._items[new_id] = item
        return item


items_service = ItemsService()
